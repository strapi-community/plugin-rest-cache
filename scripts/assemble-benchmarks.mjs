#!/usr/bin/env node

/**
 * Combines the per-provider benchmark JSON into one BENCHMARKS.md.
 *
 * The workflow used to `cat` the per-provider markdown files together, which
 * produced a document with two `# Benchmarks` titles and two Context blocks.
 * The redis half read as a stray section of the memory report, and there was
 * no way to compare a scenario across providers without scrolling between two
 * tables and holding the numbers in your head.
 *
 * So this reads the JSON instead and renders one document, with the providers
 * as columns.
 *
 * Absolute throughput is NOT comparable across providers: each matrix leg runs
 * on its own runner. Only the ratio against that leg's own cache-disabled
 * baseline is, which is why the ratio is what the summary leads with.
 *
 * Usage: node scripts/assemble-benchmarks.mjs <artifacts-dir> [--out BENCHMARKS.md]
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';

function findJson(dir) {
  const found = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) found.push(...findJson(full));
    else if (/^bench-.+\.json$/.test(entry)) found.push(full);
  }
  return found;
}

const [, , dirArg, ...rest] = process.argv;
if (!dirArg) {
  console.error('usage: assemble-benchmarks.mjs <artifacts-dir> [--out FILE]');
  process.exit(1);
}
const outIndex = rest.indexOf('--out');
const out = outIndex === -1 ? 'BENCHMARKS.md' : rest[outIndex + 1];

const reports = findJson(dirArg)
  .map((file) => JSON.parse(readFileSync(file, 'utf8')))
  .sort((a, b) => a.args.provider.localeCompare(b.args.provider));

if (!reports.length) {
  console.error(`no bench-*.json found under ${dirArg}`);
  process.exit(1);
}

const providers = reports.map((r) => r.args.provider);
const fmt = (n) => Math.round(n).toLocaleString('en-US');

// Scenario order comes from the reports themselves rather than a list here, so
// adding a scenario to benchmark.mjs does not silently drop it from the doc.
const scenarios = [];
for (const report of reports) {
  for (const result of report.results) {
    if (!scenarios.some((s) => s.id === result.id)) {
      scenarios.push({ id: result.id, name: result.name });
    }
  }
}

const resultFor = (report, id) => report.results.find((r) => r.id === id);
const baselineFor = (report) => resultFor(report, 'cache-disabled');

const ratio = (report, id) => {
  const baseline = baselineFor(report);
  const result = resultFor(report, id);
  if (!result) return null;
  if (!baseline || id === 'cache-disabled' || baseline.requests.average <= 0) return null;
  return result.requests.average / baseline.requests.average;
};

const lines = [];
lines.push('# Benchmarks');
lines.push('');
lines.push(
  '> Generated by `.github/workflows/benchmarks.yml`. Do not edit by hand - re-run the workflow instead.'
);
lines.push('');

// --- Context -------------------------------------------------------------
const first = reports[0];
lines.push('## Context');
lines.push('');
lines.push(`- Generated: \`${first.meta.generatedAt}\``);
lines.push(`- Commit: \`${first.meta.commit}\``);
lines.push(`- Plugin version: \`${first.meta.pluginVersion}\``);
lines.push(`- Strapi version: \`${first.meta.strapiVersion}\``);
lines.push(`- Endpoint: \`${first.args.path}\``);
lines.push(
  `- Load: ${first.args.connections} connections, pipelining ${first.args.pipelining}, ${first.args.duration}s per scenario (${first.args.warmup}s warmup)`
);
lines.push('');
lines.push('| Provider | Runner | Cores | Node |');
lines.push('|---|---|---:|---|');
for (const report of reports) {
  lines.push(
    `| \`${report.args.provider}\` | ${report.meta.runner} | ${report.meta.cores ?? '?'} | ${report.meta.nodeVersion ?? '?'} |`
  );
}
lines.push('');
lines.push(
  '**Read the ratios, not the absolute numbers.** Each provider runs on its own ' +
    'runner, so throughput is not comparable between the columns below, and not ' +
    'comparable between runs at all. What is meaningful is each scenario against ' +
    'the cache-disabled baseline measured on that same runner, in that same job.'
);
lines.push('');

// --- Headline ------------------------------------------------------------
lines.push('## Speedup vs cache disabled');
lines.push('');
lines.push(`| Scenario | ${providers.map((p) => `\`${p}\``).join(' | ')} |`);
lines.push(`|---|${providers.map(() => '---:').join('|')}|`);
for (const scenario of scenarios) {
  if (scenario.id === 'cache-disabled') continue;
  const cells = reports.map((report) => {
    const value = ratio(report, scenario.id);
    return value === null ? '-' : `${value.toFixed(1)}x`;
  });
  lines.push(`| ${scenario.name} | ${cells.join(' | ')} |`);
}
lines.push('');

// --- Throughput and latency ---------------------------------------------
for (const [title, render] of [
  ['Requests per second', (r) => fmt(r.requests.average)],
  ['Latency p50', (r) => `${r.latency.p50} ms`],
  ['Latency p99', (r) => `${r.latency.p99} ms`],
]) {
  lines.push(`## ${title}`);
  lines.push('');
  lines.push(`| Scenario | ${providers.map((p) => `\`${p}\``).join(' | ')} |`);
  lines.push(`|---|${providers.map(() => '---:').join('|')}|`);
  for (const scenario of scenarios) {
    const cells = reports.map((report) => {
      const result = resultFor(report, scenario.id);
      return result ? render(result) : '-';
    });
    lines.push(`| ${scenario.name} | ${cells.join(' | ')} |`);
  }
  lines.push('');
}

// --- Failures ------------------------------------------------------------
// Only 304s from the conditional scenario are expected non-2xx; benchmark.mjs
// has already separated those out. Anything reaching this table means the run
// is not trustworthy, so it is stated plainly rather than left in a footnote.
const suspect = [];
for (const report of reports) {
  for (const result of report.results) {
    const failed = result.errors + result.timeouts + (result.unexpectedNon2xx ?? 0);
    if (failed > 0) {
      suspect.push({ provider: report.args.provider, name: result.name, failed });
    }
  }
}
if (suspect.length) {
  lines.push('> [!WARNING]');
  lines.push('> **These numbers are not trustworthy.** Failed requests were recorded:');
  lines.push('>');
  for (const item of suspect) {
    lines.push(`> - \`${item.provider}\` / ${item.name}: ${item.failed} failed requests`);
  }
  lines.push('');
} else {
  lines.push('No failed requests were recorded in any scenario.');
  lines.push('');
}

// --- Scenario notes ------------------------------------------------------
lines.push('## What each scenario measures');
lines.push('');
lines.push(
  '- **Cache disabled (reference)** - the plugin is off. Every other row is measured against this.'
);
lines.push('- **Cache enabled, ETag off** - the plain cache hit path.');
lines.push('- **Cache enabled, ETag on** - as above, plus computing and sending an ETag.');
lines.push(
  '- **Cache enabled, conditional requests (304)** - what a browser or CDN does on revalidation: a matching `If-None-Match`, answered with an empty 304.'
);
lines.push(
  '- **Cache enabled, every request a distinct key** - the honest downside. Query parameters are part of the cache key, so an API called with a different filter every time stores an entry per request and reads none of them back.'
);
lines.push('');

writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`wrote ${out} (${providers.join(', ')})`);
